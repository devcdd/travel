export interface Place {
  name: string
  zh: string
  /** Google 지도 검색어 */
  q: string
  lat?: number
  lng?: number
  /** 택시 카드에 보여줄 주소 */
  address?: string
}

export type Kind = 'meet' | 'sight' | 'food' | 'free' | 'move'
export type Tone = 'ok' | 'warn' | 'idea'

export interface Alt {
  tag: string
  title: string
  zh?: string
  desc: string
  place?: Place
}

export interface Stop {
  time: string
  /** 시각이 아닌 라벨(예: '도착')이면 true */
  soft?: boolean
  kind: Kind
  kindLabel?: string
  title?: string
  zh?: string
  place?: Place
  meta?: string[]
  desc?: string
  tips?: string[]
  alts?: Alt[]
  /** 투어 버스로 이동하는 곳은 길찾기 버튼을 숨깁니다 */
  tour?: boolean
  /** 하루 동선(Google 지도 경로, 지도 경로선)에서 제외 */
  offRoute?: boolean
}

